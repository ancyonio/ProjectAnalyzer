def step01_architecture_diagrams(graph: Graph, inv: Dict[str, Any]) -> str:
    out = [_header('Step 01 — Architecture Diagrams Report',
                   'Phase 1 / Step 1 — Architecture Diagrams', graph)]
    out.append('## 1. Validation Methodology\n')
    out.append('Every element in every diagram below was emitted from a parsed artefact.\n'
               'No component, relationship or pattern was assumed. Diagram sources live in\n'
               '`generated_diagrams/` and regenerate deterministically from the same graph.\n')
    out.append('\n| Check | Result |\n|---|---|\n')
    out.append(f"| Components traced to source files | {len(graph.nodes)} nodes, "
               f"all from parsed XML |\n")
    out.append(f"| Relationships with code evidence | {len(graph.rels)} edges |\n")
    out.append('| Assumed/placeholder components | 0 |\n')
    out.append('| Remote PlantUML includes | 0 (offline-safe syntax only) |\n')

    out.append('\n## 2. System Context\n\n```mermaid\n')
    out.append(mermaid.context_diagram(graph))
    out.append('\n```\n')

    out.append('\n## 3. Container View (modules)\n\n```mermaid\n')
    out.append(mermaid.container_diagram(graph))
    out.append('\n```\n')

    out.append('\n## 4. Component View\n\n```mermaid\n')
    out.append(mermaid.component_diagram(graph))
    out.append('\n```\n')

    out.append('\n## 5. Process Dependency Graph\n\n```mermaid\n')
    out.append(mermaid.dependency_graph(graph))
    out.append('\n```\n')

    out.append('\n## 6. Schema Usage Map\n\n```mermaid\n')
    out.append(mermaid.schema_usage_map(graph))
    out.append('\n```\n')

    out.append('\n## 7. Canonical Data Model (ER)\n\n```mermaid\n')
    out.append(mermaid.er_diagram(graph))
    out.append('\n```\n')

    out.append('\n## 8. Integration Surface\n\n```mermaid\n')
    out.append(mermaid.integration_diagram(graph))
    out.append('\n```\n')

    top = sorted(graph.by_label('BWProcess'),
                 key=lambda p: -float(p.properties.get('complexityScore', 0) or 0))[:5]
    out.append('\n## 9. Key Process Flows\n')
    for proc in top:
        out.append(f'\n### {proc.name}\n\n```mermaid\n')
        out.append(mermaid.process_flow(graph, proc))
        out.append('\n```\n')

    out.append('\n## 10. Architecture Commentary\n')
    out.append(LLM_MARK.format(instruction=(
        'Explain what the diagrams above reveal: coupling patterns, layering violations, '
        'candidate service boundaries for the Spring Boot target, and which flows deserve '
        'a sequence diagram in the design phase. Reference only components drawn above.')))
    return ''.join(out)


