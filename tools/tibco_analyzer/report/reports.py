def step02_discover_baseline(graph: Graph, inv: Dict[str, Any]) -> str:
    out = [_header('Step 02 — Discover & Baseline Report',
                   'Phase 1 / Step 2 — Discover & Baseline', graph)]

    out.append('## 1. Artefact Inventory\n')
    out.append(_table(['Artefact family', 'Files'],
                      [[k, v] for k, v in (graph.meta.get('artifactFamilies') or {}).items()]))
    out.append('\n### By module\n')
    out.append(_table(['Module', 'Processes', 'Activities', 'Schemas', 'Services',
                       'Global vars', 'Shared resources', 'Entry points', 'Complexity'],
                      [[m['module'], m['processes'], m['activities'], m['schemas'],
                        m['services'], m['globalVariables'], m['sharedResources'],
                        m['entryPoints'], m['totalComplexity']] for m in inv['modules']]))

    out.append('\n## 2. Entry Points → Spring Boot Targets\n')
    out.append(_table(['Process', 'Entry type', 'Spring Boot target', 'Endpoint', 'Module'],
                      [[e['process'], e['entryType'], e['springTarget'],
                        e['endpoint'] or '-', e['module']] for e in inv['entryPoints']]))

    out.append('\n## 3. Adapter / Integration Inventory\n')
    out.append(_table(['Category', 'Spring Boot equivalent', 'Occurrences', 'Processes'],
                      [[r['category'], r['springTarget'], r['count'],
                        ', '.join(r['processes'][:6])] for r in inv['integrationSurface']]))

    out.append('\n## 4. Canonical Schema Catalog (contract freeze)\n')
    rows = []
    for xsd in sorted(graph.by_label('XSD'), key=lambda x: x.name):
        users = [graph.nodes[r.start_id].name for r in graph.incoming(xsd.node_id)
                 if r.rel_type in ('USES_XSD', 'IMPORTS_SCHEMA') and r.start_id in graph.nodes]
        rows.append([xsd.name, xsd.properties.get('namespace', ''),
                     xsd.properties.get('elementCount', 0),
                     xsd.properties.get('rootElements', ''), len(users),
                     f"`{xsd.file_path}`"])
    out.append(_table(['Schema', 'Namespace', 'Elements', 'Root elements', 'Consumers', 'File'],
                      rows))
    out.append('\n> **Contract freeze rule:** none of the namespaces or element names above '
               'may change during migration. They are the acceptance criteria for parity '
               'testing.\n')

    out.append('\n## 5. Configuration Surface (global variables)\n')
    gvars = graph.by_label('GlobalVariable')
    out.append(_table(['Variable', 'Default value', 'Module', 'Type'],
                      [[g.name, str(g.properties.get('value', ''))[:60], g.module,
                        g.properties.get('type', '')] for g in gvars[:80]]))

    out.append('\n## 6. Error Handling Baseline\n')
    out.append(_table(['Process', 'Module', 'Activities', 'Tier', 'Entry type'],
                      [[g['process'], g['module'], g['activities'], g['tier'],
                        g['entryType']] for g in inv['errorHandlingGaps'][:30]]))
    out.append('\n_Processes listed above have no error transition; the target Spring '
               'service must define explicit behaviour for their failure paths._\n')

    out.append('\n## 7. Dead Code / Out-of-Scope Candidates\n')
    out.append(_table(['Category', 'Count'],
                      [[k, v] for k, v in inv['deadCodeTotals'].items()]))

    out.append('\n## 8. Business Flow Documentation\n')
    out.append(LLM_MARK.format(instruction=(
        'For each entry point in section 2, describe the happy path, the branching '
        'conditions and the fault paths, using the per-process context packs in '
        '`context/processes/`. Do not describe a process you have not opened.')))

    out.append('\n## 9. Risk Register\n')
    out.append(LLM_MARK.format(instruction=(
        'Build a risk table (risk / likelihood / impact / mitigation / owner) from the '
        'hotspots, cycles, error-handling gaps and integration surface above.')))

    out.append('\n## 10. Success Criteria\n')
    out.append(LLM_MARK.format(instruction=(
        'Define measurable parity criteria per entry point: contract preservation, '
        'latency budget, throughput, error-rate parity, test coverage targets.')))

    out.append('\n## 11. Prioritised Migration Backlog\n')
    for wave in inv['migrationSequence']:
        out.append(f"\n### Wave {wave['wave']}\n")
        out.append(_table(['Process', 'Module', 'Tier', 'Score', 'Entry type'],
                          [[p['process'], p['module'], p['tier'], p['score'],
                            p['entryType']] for p in wave['processes']]))
    return ''.join(out)


REPORTS = {
    'Step00_TIBCO_ANALYSIS_REPORT.md': step00_graph_analysis,
    'Step01_ARCHITECTURE_DIAGRAMS_REPORT.md': step01_architecture_diagrams,
    'Step02_DISCOVER_AND_BASELINE_REPORT.md': step02_discover_baseline,
}


def generate_reports(graph: Graph, output_dir: Path,
                     inventory: Dict[str, Any] | None = None) -> Dict[str, str]:
    inv = inventory if inventory is not None else full_inventory(graph)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    written = {}
    for name, fn in REPORTS.items():
        path = output_dir / name
        path.write_text(fn(graph, inv), encoding='utf-8')
        written[name] = str(path)
    return written
