def step00_graph_analysis(graph: Graph, inv: Dict[str, Any]) -> str:
    stats = inv['stats']
    out = [_header('Step 00 — TIBCO Graph Analysis Report',
                   'Phase 1 / Step 0 — Neo4j Analysis', graph)]
    out.append('## 1. Executive Summary\n')
    out.append(LLM_MARK.format(instruction=(
        'Summarise the estate in 5-8 sentences using ONLY the tables in this report: '
        'size, dominant entry-point style, complexity concentration, the top three '
        'migration risks, and the recommended first wave. Cite counts explicitly.')))

    out.append('\n## 2. Graph Statistics\n')
    out.append(_table(['Metric', 'Value'],
                      [['Total nodes', stats['totalNodes']],
                       ['Total relationships', stats['totalRelationships']],
                       ['Node labels', len(stats['nodeCounts'])],
                       ['Relationship types', len(stats['relationshipCounts'])]]))
    out.append('\n### Nodes by label\n')
    out.append(_table(['Label', 'Count'], [[k, v] for k, v in stats['nodeCounts'].items()]))
    out.append('\n### Relationships by type\n')
    out.append(_table(['Type', 'Count'],
                      [[k, v] for k, v in stats['relationshipCounts'].items()]))

    out.append('\n## 3. Artefact Inventory\n')
    out.append(_table(['Artefact family', 'Files'],
                      [[k, v] for k, v in (graph.meta.get('artifactFamilies') or {}).items()]))

    out.append('\n## 4. Complexity Ranking\n')
    out.append(_table(['#', 'Process', 'Module', 'Tier', 'Score', 'Activities',
                       'Transitions', 'Error handlers', 'Schemas', 'Called by'],
                      [[i, r['process'], r['module'], r['tier'], r['score'],
                        r['activities'], r['transitions'], r['errorHandlers'],
                        r['schemas'], r['calledBy']]
                       for i, r in enumerate(inv['complexity']['ranking'][:40], 1)]))
    out.append('\n### Tier distribution\n')
    out.append(_table(['Tier', 'Processes'],
                      [[k, v] for k, v in inv['complexity']['tierDistribution'].items()]))

    out.append('\n## 5. Entry Point Catalog\n')
    out.append(_table(['Process', 'Entry type', 'Spring Boot target', 'Endpoint', 'Module', 'Tier'],
                      [[e['process'], e['entryType'], e['springTarget'],
                        e['endpoint'] or '-', e['module'], e['tier']]
                       for e in inv['entryPoints']]))

    out.append('\n## 6. Change Hotspots (blast-radius ranking)\n')
    out.append(_table(['Type', 'Name', 'Module', 'Dependents', 'Relation types'],
                      [[h['type'], h['name'], h['module'], h['dependents'],
                        ', '.join(h['relationTypes'])] for h in inv['hotspots']]))

    out.append('\n## 7. Dead Code Inventory\n')
    totals = inv['deadCodeTotals']
    out.append(_table(['Category', 'Count'], [[k, v] for k, v in totals.items()]))
    for key, rows in inv['deadCode'].items():
        out.append(f'\n### {key} ({len(rows)})\n')
        if rows:
            headers = sorted({k for r in rows for k in r})
            out.append(_table(headers, [[r.get(h, '') for h in headers] for r in rows]))
        else:
            out.append('_None found._\n')
    if sum(totals.values()) == 0:
        out.append('\nNo dead code detected — every artefact is referenced.\n')

    out.append('\n## 8. Circular Dependencies (migration blockers)\n')
    cycles = inv['circularDependencies']
    if cycles:
        for cycle in cycles[:25]:
            out.append(f"- `{' -> '.join(cycle)}`\n")
    else:
        out.append('_None detected._\n')

    out.append('\n## 9. Recommended Migration Sequence\n')
    for wave in inv['migrationSequence']:
        out.append(f"\n### Wave {wave['wave']}"
                   + (f" — {wave['note']}" if wave['note'] else '') + '\n')
        out.append(_table(['Process', 'Module', 'Tier', 'Score', 'Entry type'],
                          [[p['process'], p['module'], p['tier'], p['score'],
                            p['entryType']] for p in wave['processes']]))

    out.append('\n## 10. Migration Risk Assessment\n')
    out.append(LLM_MARK.format(instruction=(
        'For each Critical/High tier process and each top-5 hotspot, state the specific '
        'migration risk and the mitigation. Reference only artefacts named above.')))

    out.append('\n## 11. Neo4j Import & Verification\n')
    out.append('Artefacts produced alongside this report:\n\n'
               '- `neo4j_nodes.csv`, `neo4j_relationships.csv` — admin-import pair\n'
               '- `neo4j_import.cypher` — runnable in Neo4j Browser / cypher-shell\n'
               '- `analysis_queries.cypher` — verification and analysis cookbook\n'
               '- `validation_report.md` — referential-integrity gate result\n\n'
               '```bash\n'
               'neo4j-admin database import full \\\n'
               '  --nodes=neo4j_nodes.csv \\\n'
               '  --relationships=neo4j_relationships.csv \\\n'
               '  --database=tibco-migration --overwrite-destination\n'
               '```\n')

    out.append('\n## 12. Migration Readiness Checklist\n')
    out.append(_table(['Deliverable', 'Status', 'Evidence'], [
        ['Knowledge graph built', 'DONE', f"{stats['totalNodes']} nodes / {stats['totalRelationships']} rels"],
        ['Neo4j CSV + Cypher exported', 'DONE', 'neo4j_nodes.csv, neo4j_relationships.csv, neo4j_import.cypher'],
        ['Graph validated', 'DONE', 'validation_report.md'],
        ['Complexity scored', 'DONE', f"{len(inv['complexity']['ranking'])} processes"],
        ['Entry points catalogued', 'DONE', f"{len(inv['entryPoints'])} entry points"],
        ['Dead code inventoried', 'DONE', f"{sum(totals.values())} unreferenced artefacts"],
        ['Migration sequence proposed', 'DONE', f"{len(inv['migrationSequence'])} waves"],
        ['Risk narrative written', 'PENDING LLM', 'Section 10'],
        ['Executive summary written', 'PENDING LLM', 'Section 1'],
    ]))
    return ''.join(out)


