"""Report scaffolding.

The analyzer writes the *facts* half of each step report — tables, counts,
diagrams, checklists — and leaves explicitly marked `<!-- LLM: ... -->` slots
for the narrative half. Copilot fills those slots and nothing else, so the
numbers in a delivered report can always be traced back to a parse.
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

from ..analysis.inventory import full_inventory
from ..diagrams import mermaid
from ..model import Graph
from .markdown import table_lines

LLM_MARK = ('<!-- LLM: {instruction} -->\n'
            '_(pending narrative — generated by the Copilot prompt for this step)_\n')


def _table(headers: List[str], rows: List[List[Any]]) -> str:
    if not rows:
        return '_No data._\n'
    return '\n'.join(table_lines(headers, rows)) + '\n'


def _header(title: str, step: str, graph: Graph) -> str:
    meta = graph.meta or {}
    return '\n'.join([
        f'# {title}',
        '',
        f'> **Step:** {step}  ',
        f'> **Source:** `{meta.get("tibcoRoot", "n/a")}`  ',
        f'> **Analyzer run:** {meta.get("generatedAt", "n/a")}  ',
        f'> **Report scaffolded:** {datetime.now(timezone.utc).isoformat()}  ',
        '> **Provenance:** every table below is generated from the parsed knowledge '
        'graph. Narrative sections marked `LLM` are written by Copilot from these '
        'facts only.',
        '',
    ])


